// Regenerates supabase/seed.sql from the demo dataset. Run: node scripts/generate-seed.mjs
import { writeFileSync } from "node:fs";
import { DEMO_MOTORCYCLES } from "../lib/motorcycles/data.ts";

const q = (v) => (v === null || v === undefined ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;

const rows = DEMO_MOTORCYCLES.map(
  (m) =>
    `(${[
      q(m.slug), q(m.name), q(m.market), q(m.modelYear), q(m.category), q(m.description), q(m.engineCc),
      q(m.power?.value ?? null), q(m.power?.unit ?? null), q(m.torque?.value ?? null), q(m.torque?.unit ?? null),
      q(m.transmission), q(m.cooling), q(m.kerbWeightKg), q(m.seatHeightMm), q(m.fuelCapacityL), arr(m.features), q(m.availability), "true",
    ].join(", ")})`,
);

const sql = `-- GENERATED by scripts/generate-seed.mjs. DEMO DATA ONLY: unverified, no prices, no source URLs.
-- Do not present these rows as verified current market inventory. Published so the demo lineup is visible; unpublish any you do not want.
-- Requires migration 0002 (adds is_published).
insert into public.motorcycles
  (slug, name, market, model_year, category, description, engine_cc, power_value, power_unit, torque_value, torque_unit,
   transmission, cooling, kerb_weight_kg, seat_height_mm, fuel_capacity_l, features, availability_status, is_published)
values
${rows.join(",\n")}
on conflict (slug) do nothing;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote seed.sql with ${rows.length} demo motorcycles`);
